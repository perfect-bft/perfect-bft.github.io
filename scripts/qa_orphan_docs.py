# -*- coding: utf-8 -*-
"""找出 docs/ 下「没有被 sidebars.js 引用」的文档。

注意：sidebars.js 用 autogenerated 时会整目录自动收录，这类不算孤儿。
用法：python scripts/qa_orphan_docs.py
"""
import re, os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(BASE, 'docs')
SIDEBAR = os.path.join(BASE, 'sidebars.js')

txt = open(SIDEBAR, encoding='utf-8').read()
explicit = set(re.findall(r"id: '([^']+)'", txt))          # 显式 { type:'doc', id:'...' }
auto_dirs = re.findall(r"dirName: '([^']+)'", txt)          # autogenerated 目录


def doc_candidates(path):
    """一个 md 文件在 sidebars.js 里可能被写成两种 id：
       docs/foo/bar/index.md -> 'foo/bar' 或 'foo/bar/index'
       两者任一被引用都算已收录。
    """
    rel = os.path.relpath(path, DOCS).replace(os.sep, '/')
    rel = re.sub(r'\.mdx?$', '', rel)
    cands = {rel}
    if rel.endswith('/index'):
        cands.add(rel[: -len('/index')])
    elif rel == 'index':
        cands.add('')
    return cands


all_docs = []           # [(显示名, 候选 id 集合, 文件路径)]
for dp, dn, fn in os.walk(DOCS):
    for f in fn:
        if f.lower().endswith(('.md', '.mdx')):
            p = os.path.join(dp, f)
            all_docs.append((os.path.relpath(p, DOCS).replace(os.sep, '/'),
                             doc_candidates(p), p))


def covered(cands):
    if cands & explicit:
        return True
    for a in auto_dirs:                      # autogenerated 覆盖其整个子树
        for c in cands:
            if c == a or c.startswith(a.rstrip('/') + '/'):
                return True
    return False


orphans = sorted(name for name, cands, _ in all_docs if not covered(cands))
orphan_paths = {name: p for name, cands, p in all_docs if not covered(cands)}

print(f'docs 下 md/mdx: {len(all_docs)} 个')
print(f'sidebars.js 显式 id: {len(explicit)} 个；autogenerated 目录: {len(auto_dirs)} 个 -> {auto_dirs}')
print(f'\n=== 未被引用的文档（会生成页面但侧边栏找不到）: {len(orphans)} ===')
for d in orphans:
    p = orphan_paths[d]
    try:
        lines = sum(1 for _ in open(p, encoding='utf-8'))
    except Exception:
        lines = -1
    title = ''
    try:
        for ln in open(p, encoding='utf-8'):
            if ln.startswith('title:'):
                title = ln.strip()[6:].strip()
                break
    except Exception:
        pass
    flag = ' [空占位]' if lines <= 12 else ''
    print(f'  {lines:>4} 行  {d:<34} {title}{flag}')
